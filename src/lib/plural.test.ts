/**
 * Тесты плюрализации. Запуск: npm test
 *
 * Проверяются именно те числа, на которых правило обычно ломается:
 * 11–14 (берут форму «многих», хотя оканчиваются на 1–4) и переходы
 * через сотню.
 */
import { plural, pluralize, FORMS } from "./plural";

const forms = FORMS.direction; // направление / направления / направлений

const cases: [number, string][] = [
  [0, "направлений"],
  [1, "направление"],
  [2, "направления"],
  [3, "направления"],
  [4, "направления"],
  [5, "направлений"],
  [10, "направлений"],
  // Ловушка: оканчиваются на 1–4, но форма — «многих».
  [11, "направлений"],
  [12, "направлений"],
  [13, "направлений"],
  [14, "направлений"],
  [15, "направлений"],
  [21, "направление"],
  [22, "направления"],
  [25, "направлений"],
  [100, "направлений"],
  [101, "направление"],
  [102, "направления"],
  // Вторая ловушка: 111–114 снова форма «многих».
  [111, "направлений"],
  [112, "направлений"],
  [121, "направление"],
  [1001, "направление"],
];

let failed = 0;

for (const [n, expected] of cases) {
  const actual = plural(n, forms);
  if (actual !== expected) {
    console.error(`✗ plural(${n}) = "${actual}", ожидалось "${expected}"`);
    failed++;
  }
}

// Отрицательные и дробные не должны падать.
if (plural(-1, forms) !== "направление") {
  console.error("✗ plural(-1) должен работать как plural(1)");
  failed++;
}
if (plural(1.7, forms) !== "направление") {
  console.error("✗ plural(1.7) должен усекаться до 1");
  failed++;
}
if (pluralize(5, forms) !== "5 направлений") {
  console.error("✗ pluralize должен склеивать число и форму");
  failed++;
}

if (failed > 0) {
  console.error(`\nПровалено проверок: ${failed}`);
  process.exit(1);
}

console.log(`Плюрализация: все ${cases.length + 3} проверки пройдены.`);
