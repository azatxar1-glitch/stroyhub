/**
 * Поиск по подстроке без учёта регистра и буквы «ё».
 * Совпадения с начала названия идут первыми: набирая «нов», человек
 * скорее ищет Новосибирск, чем Комсомольск-на-Амуре.
 */
export function searchCities(query: string, limit = 8): string[] {
  const q = normalize(query.trim());
  if (!q) return CITIES.slice(0, limit);

  const starts: string[] = [];
  const contains: string[] = [];

  for (const city of CITIES) {
    const normalized = normalize(city);
    if (normalized.startsWith(q)) starts.push(city);
    else if (normalized.includes(q)) contains.push(city);
    if (starts.length >= limit) break;
  }

  return [...starts, ...contains].slice(0, limit);
}

function normalize(value: string): string {
  return value.toLowerCase().replace(/ё/g, "е");
}
